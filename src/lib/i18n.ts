const DICTS: Record<Lang, Record<Key, string>> = { en, kn, hi };

/** Text in the chosen language, with {placeholders} filled in. */
export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  let text = DICTS[lang]?.[key] ?? en[key];
  for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

/** Dish or category name in the chosen language, falling back to English. */
export function localName(lang: Lang, v: { name: string; nameKn?: string; nameHi?: string }): string {
  if (lang === "kn" && v.nameKn) return v.nameKn;
  if (lang === "hi" && v.nameHi) return v.nameHi;
  return v.name;
}
